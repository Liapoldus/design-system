import assert from 'node:assert/strict'
import { cp, mkdir, mkdtemp, readFile, readdir, rm, writeFile } from 'node:fs/promises'
import { dirname, join, relative, resolve } from 'node:path'
import { tmpdir } from 'node:os'
import { execFileSync } from 'node:child_process'
import { existsSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { optimize } from 'svgo'
import svgoConfig from '../svgo.config.mjs'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const sourceRoots = ['logo', 'icons', 'mascots', 'fonts']
const dist = join(root, 'dist')
const marker = join(dist, '.liapoldus-generated')

try {
  await readFile(marker)
  await rm(dist, { recursive: true, force: true })
} catch (error) {
  if (error.code !== 'ENOENT') throw error
  try {
    await readdir(dist)
    throw new Error('Refusing to replace dist/: missing generated-output marker')
  } catch (directoryError) {
    if (directoryError.code !== 'ENOENT') throw directoryError
  }
}

await mkdir(dist, { recursive: true })
await writeFile(marker, 'Generated by scripts/build-package-assets.mjs\n')
const temporaryDirectory = await mkdtemp(join(tmpdir(), 'liapoldus-svg-build-'))
const fontConfig = join(temporaryDirectory, 'fonts.conf')
const systemFontConfig = ['/opt/homebrew/etc/fonts/fonts.conf', '/etc/fonts/fonts.conf'].find(existsSync)
const fontConfigInclude = systemFontConfig ? `<include>${systemFontConfig}</include>` : ''
await writeFile(fontConfig, `<?xml version="1.0"?><fontconfig><dir>${join(root, 'assets/fonts')}</dir><cachedir>${join(temporaryDirectory, 'cache')}</cachedir>${fontConfigInclude}</fontconfig>`)

async function walk(directory) {
  const files = []
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const full = join(directory, entry.name)
    if (entry.isDirectory()) files.push(...await walk(full))
    else files.push(full)
  }
  return files
}

function optimizeSvg(svg, file) {
  return optimize(svg, { ...svgoConfig, path: file })
}

for (const name of sourceRoots) {
  const source = join(root, 'assets', name)
  for (const file of await walk(source)) {
    const target = join(dist, name, relative(source, file))
    await mkdir(dirname(target), { recursive: true })
    if (file.endsWith('.svg')) {
      const result = optimizeSvg(await readFile(file, 'utf8'), file)
      let optimizedSvg = result.data
      if (name === 'logo' && optimizedSvg.includes('<text')) {
        const expanded = join(temporaryDirectory, `${relative(source, file).replaceAll('/', '-')}`)
        execFileSync('inkscape', [
          file,
          '--export-text-to-path',
          '--export-plain-svg',
          `--export-filename=${expanded}`,
        ], { env: { ...process.env, FONTCONFIG_FILE: fontConfig }, stdio: 'pipe' })
        const outlined = await readFile(expanded, 'utf8')
        assert.ok(!outlined.includes('<text'), `Inkscape did not outline logo text in ${file}`)
        optimizedSvg = optimizeSvg(outlined, file).data
      }
      assert.ok(optimizedSvg.includes('viewBox='), `SVGO removed viewBox from ${file}`)
      assert.ok(optimizedSvg.includes('<title'), `SVGO removed accessible title from ${file}`)
      await writeFile(target, `${optimizedSvg}\n`)
    } else {
      await cp(file, target)
    }
  }
}

await rm(temporaryDirectory, { recursive: true, force: true })
process.stdout.write(`Built optimized package assets in ${dist}\n`)
